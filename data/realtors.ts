// Helper: get realtors for a specific city
export function getRealtorsByCity(city: string): Realtor[] {
  return texasRealtors.filter(
    (r) => r.city.toLowerCase() === city.toLowerCase()
  )
}

// Helper: get top 3 realtors for a city sorted by rating then review count
export function getTopRealtors(city: string, limit = 3): Realtor[] {
  return getRealtorsByCity(city)
    .sort((a, b) => {
      if (b.rating !== a.rating) return b.rating - a.rating
      return b.reviewCount - a.reviewCount
    })
    .slice(0, limit)
}

